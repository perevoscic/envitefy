import { createHash, randomUUID } from "node:crypto";
import { spawn } from "node:child_process";
import { constants } from "node:fs";
import { copyFile, mkdir, readFile, realpath, stat, unlink, writeFile } from "node:fs/promises";
import path from "node:path";

const sha256 = bytes => createHash("sha256").update(bytes).digest("hex");

function inside(root, candidate) {
  const relative = path.relative(root, candidate);
  return Boolean(relative && !relative.startsWith("..") && !path.isAbsolute(relative));
}

async function scopedPath(runDir, candidate, { createParent = false } = {}) {
  const root = await realpath(path.resolve(runDir));
  const target = path.resolve(candidate);
  if (!inside(root, target)) throw new Error("Artwork path must stay inside the campaign run directory.");
  let ancestor = path.dirname(target);
  while (true) {
    try {
      const resolved = await realpath(ancestor);
      if (resolved !== root && !inside(root, resolved)) throw new Error("Artwork path cannot follow a link outside its campaign directory.");
      break;
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
      ancestor = path.dirname(ancestor);
    }
  }
  if (createParent) await mkdir(path.dirname(target), { recursive: true });
  try {
    const resolved = await realpath(target);
    if (!inside(root, resolved)) throw new Error("Artwork path cannot follow a link outside its campaign directory.");
    return resolved;
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    return target;
  }
}

function rasterFormat(bytes) {
  if (bytes.subarray(0, 8).equals(Buffer.from("89504e470d0a1a0a", "hex"))) return "png";
  if (bytes.subarray(0, 3).equals(Buffer.from("ffd8ff", "hex"))) return "jpeg";
  if (bytes.subarray(0, 4).toString("ascii") === "RIFF" && bytes.subarray(8, 12).toString("ascii") === "WEBP") return "webp";
  throw new Error("Generated artwork must contain PNG, JPEG, or WebP raster bytes.");
}

function rejectAnimatedWebp(bytes) {
  for (let offset = 12; offset + 8 <= bytes.length;) {
    const type = bytes.subarray(offset, offset + 4).toString("ascii");
    if (type === "ANIM" || type === "ANMF") throw new Error("Animated WebP requires a separate animation-preserving archive.");
    const size = bytes.readUInt32LE(offset + 4);
    offset += 8 + size + size % 2;
  }
}

function execute(binary, args, limit = 80 * 1024 * 1024) {
  return new Promise((resolve, reject) => {
    const child = spawn(binary, args, { windowsHide: true, shell: false, stdio: ["ignore", "pipe", "pipe"] });
    const output = []; let size = 0; let errorText = ""; let exceeded = false;
    const timeout = setTimeout(() => { child.kill(); }, 60_000);
    child.stdout.on("data", chunk => { size += chunk.length; if (size > limit) { exceeded = true; child.kill(); } else output.push(chunk); });
    child.stderr.on("data", chunk => { errorText = (errorText + chunk).slice(-2000); });
    child.once("error", error => { clearTimeout(timeout); reject(error); });
    child.once("close", code => {
      clearTimeout(timeout);
      if (code !== 0 || exceeded) reject(new Error(`${path.basename(binary)} failed artwork verification${exceeded ? ": decoded image too large" : `: ${errorText.trim() || code}`}`));
      else resolve(Buffer.concat(output));
    });
  });
}

async function inspectRaster(file, { ffmpegPath, ffprobePath }) {
  const probe = JSON.parse((await execute(ffprobePath, ["-v", "error", "-count_frames", "-select_streams", "v:0", "-show_entries", "stream=width,height,pix_fmt,nb_read_frames", "-of", "json", file], 100_000)).toString("utf8"));
  const stream = probe.streams?.[0];
  if (!stream?.width || !stream?.height || Number(stream.nb_read_frames || 1) !== 1) throw new Error("Artwork must decode as one complete raster frame.");
  const rgba = await execute(ffmpegPath, ["-hide_banner", "-loglevel", "error", "-nostdin", "-i", file, "-frames:v", "1", "-pix_fmt", "rgba", "-f", "rawvideo", "pipe:1"]);
  if (rgba.length !== stream.width * stream.height * 4) throw new Error("Artwork decode dimensions do not match its pixels.");
  const alpha = Buffer.alloc(stream.width * stream.height);
  let hasTransparency = false;
  for (let index = 0; index < alpha.length; index++) {
    alpha[index] = rgba[index * 4 + 3];
    if (alpha[index] !== 255) hasTransparency = true;
  }
  return { width: stream.width, height: stream.height, hasTransparency, alpha };
}

/** Archives newly generated bytes only. Existing user uploads must not be passed as originals. */
export async function archiveGeneratedArtwork({ bytes, targetPath, runDir, ffmpegPath = "ffmpeg", ffprobePath = "ffprobe" }) {
  const originalBytes = Buffer.from(bytes);
  const sourceFormat = rasterFormat(originalBytes);
  if (sourceFormat === "webp") rejectAnimatedWebp(originalBytes);
  const finalWebp = await scopedPath(runDir, targetPath, { createParent: true });
  if (path.extname(finalWebp).toLowerCase() !== ".webp") throw new Error("Final generated artwork path must end in .webp.");
  const unique = randomUUID();
  const stem = path.basename(finalWebp, ".webp");
  const sourcePath = path.join(path.dirname(finalWebp), `${stem}.generated-original-${unique}.${sourceFormat}`);
  const pendingPath = path.join(path.dirname(finalWebp), `${stem}.pending-${unique}.webp`);
  const binaries = { ffmpegPath, ffprobePath };
  await writeFile(sourcePath, originalBytes, { flag: "wx" });
  try {
    const before = await inspectRaster(sourcePath, binaries);
    if (sourceFormat === "webp") await copyFile(sourcePath, pendingPath, constants.COPYFILE_EXCL);
    else await execute(ffmpegPath, ["-hide_banner", "-loglevel", "error", "-nostdin", "-n", "-i", sourcePath, "-frames:v", "1", "-c:v", "libwebp", "-quality", "85", "-compression_level", "6", pendingPath], 100_000);
    const finalBytes = await readFile(pendingPath);
    if (rasterFormat(finalBytes) !== "webp") throw new Error("Encoded output is not an actual WebP file.");
    const after = await inspectRaster(pendingPath, binaries);
    if (after.width !== before.width || after.height !== before.height) throw new Error("WebP dimensions changed during archival.");
    if (!after.alpha.equals(before.alpha)) throw new Error("WebP transparency changed during archival.");
    await copyFile(pendingPath, finalWebp, constants.COPYFILE_EXCL);
    const finalHash = sha256(finalBytes);
    if (sha256(await readFile(finalWebp)) !== finalHash) throw new Error("Final WebP differs from its verified output.");
    // Only these exact files were created by this invocation; no globs or folder cleanup.
    await unlink(await scopedPath(runDir, sourcePath));
    await unlink(await scopedPath(runDir, pendingPath));
    return { finalWebp, finalWebpPath: finalWebp, sourceHash: sha256(originalBytes), finalHash,
      sourceFormat, sourceBytes: originalBytes.length, finalBytes: finalBytes.length,
      width: after.width, height: after.height, hasTransparency: after.hasTransparency,
      encoding: sourceFormat === "webp" ? "verified-original-webp" : "ffmpeg-libwebp-quality85-compression6",
      originalPath: sourcePath, originalDeleted: true,
      verification: { magic: true, decoded: true, dimensionsPreserved: true, alphaPreserved: true } };
  } catch (error) {
    // Preserve the generated source on conversion/verification failure for recovery.
    error.originalPath = sourcePath;
    error.targetPath = finalWebp;
    throw error;
  }
}

/** Cleanup only caller-identified generated copies with matching bytes and a verified final file.
 * Local blob URLs are live app references: leave them until their owning flow migrates URLs.
 * App-generated blobs normally already use WebP through media-upload.ts.
 */
export async function cleanupVerifiedArtworkOriginals({ runDir, artifact, originalPaths = [], ffmpegPath = "ffmpeg", ffprobePath = "ffprobe" }) {
  const finalWebp = await scopedPath(runDir, artifact.finalWebp || artifact.finalWebpPath);
  const finalBytes = await readFile(finalWebp);
  if (rasterFormat(finalBytes) !== "webp" || sha256(finalBytes) !== artifact.finalHash) throw new Error("Original cleanup requires the matching verified final WebP.");
  const decoded = await inspectRaster(finalWebp, { ffmpegPath, ffprobePath });
  if (decoded.width !== artifact.width || decoded.height !== artifact.height) throw new Error("Original cleanup dimensions no longer match.");
  const decisions = [];
  for (const originalPath of originalPaths) {
    const file = await scopedPath(runDir, originalPath);
    if (!/\.(?:png|jpe?g)$/i.test(file)) throw new Error("Only exact generated PNG/JPEG originals may be removed.");
    const relative = path.relative(await realpath(path.resolve(runDir)), file).split(path.sep).join("/");
    if (relative.startsWith("runtime/blobs/")) { decisions.push({ path: file, deleted: false, reason: "live_blob_requires_url_migration" }); continue; }
    const bytes = await readFile(file);
    if (sha256(bytes) !== artifact.sourceHash) throw new Error("Original copy does not match the generated source hash.");
    decisions.push({ path: file, deleted: false, reason: null, byteLength: (await stat(file)).size });
  }
  // Validate the whole list before deleting any copy.
  for (const decision of decisions) {
    if (decision.reason) continue;
    if (sha256(await readFile(decision.path)) !== artifact.sourceHash) throw new Error("Original changed before cleanup; retained.");
    await unlink(decision.path);
    decision.deleted = true;
  }
  return decisions;
}
