const directions = {};
for (const [category, rows] of Object.entries(groups)) {
  for (const row of rows.trim().split("\n")) {
    const [id, silhouette, binding, heading, layout, wash] = row.trim().split(/\s+/);
    if (!wash || directions[`${category}/${id}`]) throw new Error(`Invalid direction: ${row}`);
    directions[`${category}/${id}`] = { silhouette, binding, heading, layout, wash };
  }
}
if (require.main === module) {
  const target = path.join(__dirname, "../src/data/celebration-art-directions.json");
  fs.writeFileSync(target, `${JSON.stringify(directions, null, 2)}\n`);
  console.log(
    `Built ${Object.keys(directions).length} celebration art directions, without SVG backgrounds.`,
  );
}
module.exports = { directions };
