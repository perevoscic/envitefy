const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const test = require("node:test");
const { chromium } = require("playwright");
const buildBunFixture = require("./lib/build-bun-fixture.cjs");
const output = path.resolve("output/gymnastics-schedule-import");
const origin = "http://localhost:43131";
const imported = { days: [{ isoDate: "", sessions: [{ code: "A1", label: "Imported juniors", group: "Level 6", startTime: "9 AM", warmupTime: "8:30 AM", note: "Bring grips", clubs: ["Host Gym"] }, { code: "A3", label: "Evening finals", group: "Level 9", startTime: "6 PM", warmupTime: "5:30 PM", note: "", clubs: [] }] }, { isoDate: "2027-04-11", sessions: [{ code: "A2", label: "Senior session", group: "Level 8", startTime: "1 PM", warmupTime: "", note: "", clubs: [] }] }], source: { text: "Session A1 Level 6 8:30 AM 9 AM Host Gym" } };
const file = { name: "schedule.jpg", mimeType: "image/jpeg", buffer: Buffer.from("schedule photo") };

test("schedule upload and camera review preserve sessions, explicit saves and cancellation across phone/desktop and light/dark", { timeout: 90_000 }, async () => {
  buildBunFixture("scripts/build-generated-gymnastics-layout-fixture.mjs", { env: { ...process.env, GYMNASTICS_LAYOUT_FIXTURE_OUTPUT: output } });
  const script = fs.readFileSync(path.join(output, "fixture.js"));
  const css = fs.readFileSync(path.join(output, "template-editor-route.css"), "utf8");
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, reducedMotion: "reduce" });
  page.setDefaultTimeout(8000);
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  let mode = "success", release, requests = 0;
  await page.route("**/*", async route => {
    const url = new URL(route.request().url());
    if (url.origin !== origin) return route.abort();
    if (url.pathname === "/api/gymnastics/schedule") {
      requests++;
      assert.match(route.request().headers()["content-type"], /multipart\/form-data/);
      assert.match(route.request().postDataBuffer().toString(), /schedule\.jpg/);
      if (mode === "slow") await new Promise(resolve => { release = resolve; });
      return route.fulfill({ status: mode === "error" ? 422 : 200, contentType: "application/json", body: JSON.stringify(mode === "error" ? { error: "Try a clearer schedule photo." } : imported) }).catch(() => {});
    }
    if (url.pathname === "/fixture.js") return route.fulfill({ contentType: "text/javascript", body: script });
    return route.fulfill({ contentType: "text/html", body: `<!doctype html><html${url.searchParams.has("dark") ? ' class="dark" style="--app-surface:#251f2e;--app-surface-alt:#302738;--app-field-background:#302738;--app-foreground:#eee7f4;--app-muted-foreground:#bfb2cb;--app-border:#50445d;--app-input:#887596"' : ""}><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>${css}*{box-sizing:border-box}body{margin:0;font-family:Arial,sans-serif}button{font-family:inherit;background:transparent}a{color:inherit}.sr-only{position:absolute;width:1px;height:1px;padding:0;margin:-1px;overflow:hidden;clip:rect(0,0,0,0);white-space:nowrap;border:0}</style></head><body><main id="root"></main><script src="/fixture.js"></script></body></html>` });
  });
  try {
    for (const width of [1280, 375]) for (const dark of [false, true]) {
      await page.setViewportSize({ width, height: 900 });
      await page.goto(`${origin}/`);
      await page.evaluate(() => localStorage.removeItem("gymnastics-tab-sync"));
      const href = `${origin}/?schedule-editor&editing&saved-tabs&tabs${dark ? "&dark" : ""}`;
      await page.goto(href);
      await page.getByRole("button", { name: "Add tab", exact: true }).click();
      const dialog = page.locator("dialog").filter({ has: page.getByRole("button", { name: "Close section panel", exact: true }) });
      const review = page.getByRole("dialog", { name: "Review imported schedule", exact: true });
      const progress = page.getByRole("dialog", { name: "Importing schedule", exact: true });
      await dialog.getByRole("button", { name: "Schedule", exact: true }).click();
      await dialog.getByRole("button", { name: "Done", exact: true }).click();
      await page.getByRole("button", { name: "Add schedule", exact: true }).click();
      await dialog.getByRole("button", { name: "Add Day", exact: true }).click();
      await dialog.getByLabel("Date", { exact: true }).fill("2027-04-10");
      await dialog.getByRole("button", { name: "Add to event", exact: true }).click();
      await dialog.waitFor({ state: "hidden" });
      await page.getByRole("button", { name: "Edit Saturday, April 10, 2027", exact: true }).click();
      await dialog.getByRole("button", { name: "Add Session", exact: true }).click();
      await dialog.getByLabel("Session title", { exact: true }).fill("Authored finals");
      await dialog.getByRole("button", { name: "Done", exact: true }).click();
      await page.getByRole("button", { name: "Save fixture", exact: true }).click();
      const before = await page.evaluate(() => localStorage.getItem("gymnastics-tab-sync"));
      await page.getByRole("button", { name: "Edit schedule", exact: true }).click();
      assert.equal(await dialog.locator('input[capture="environment"]').getAttribute("accept"), "image/*");
      const uploadBounds = await dialog.getByRole("button", { name: "Upload schedule", exact: true }).boundingBox();
      const dayBounds = await dialog.getByRole("button", { name: "Add Day", exact: true }).boundingBox();
      assert.ok(uploadBounds.y < dayBounds.y, "import actions appear before manual dates");
      for (const name of ["Add Day", "Add Week", "Add Month"]) assert.equal(await dialog.getByRole("button", { name, exact: true }).locator("svg").count(), 1);
      await page.screenshot({ path: path.join(output, `schedule-panel-${width}-${dark ? "dark" : "light"}.png`) });
      const chooser = page.waitForEvent("filechooser");
      await dialog.getByRole("button", { name: "Upload schedule", exact: true }).click();
      await (await chooser).setFiles(file);
      await review.waitFor();
      await review.getByRole("button", { name: "Add to event schedule", exact: true }).click();
      await review.getByRole("alert").getByText("Choose a date for every imported day before adding it.", { exact: true }).waitFor();
      await review.getByLabel("Day 1 date", { exact: true }).fill("2027-04-10");
      assert.equal(await review.getByRole("alert").count(), 0, "correcting the date clears its validation message");
      await review.getByLabel("Session title", { exact: true }).first().fill("Reviewed juniors");
      await page.screenshot({ path: path.join(output, `schedule-review-${width}-${dark ? "dark" : "light"}.png`) });
      assert.equal(await review.evaluate(el => el.scrollWidth > el.clientWidth), false);
      assert.equal(await review.evaluate(el => el.contains(document.activeElement)), true);
      await page.keyboard.press("Tab");
      assert.equal(await review.evaluate(el => el.contains(document.activeElement)), true);
      await review.getByRole("button", { name: "Add to event schedule", exact: true }).click();
      assert.equal(await page.evaluate(() => localStorage.getItem("gymnastics-tab-sync")), before, "adding never saves the event");
      await dialog.getByRole("button", { name: "Done", exact: true }).click();
      await page.getByRole("heading", { name: "Authored finals", exact: true }).waitFor();
      await page.getByRole("heading", { name: "Reviewed juniors", exact: true }).waitFor();
      const calendar = page.locator('section[aria-label="Meet schedule"]');
      assert.deepEqual(await calendar.getByRole("group", { name: "Schedule periods" }).getByRole("button").allTextContents(), ["Sat, Apr 10, 2027", "Sun, Apr 11, 2027"]);
      assert.equal(await calendar.getByText("April 2027", { exact: true }).count(), 0, "two imported dates never expand into a month");
      await page.screenshot({ path: path.join(output, `schedule-provided-dates-${width}-${dark ? "dark" : "light"}.png`) });
      await page.getByRole("button", { name: "Save fixture", exact: true }).click();
      await page.reload();
      await page.getByRole("tab", { name: "Schedule", exact: true }).click();
      assert.deepEqual(await calendar.getByRole("group", { name: "Schedule periods" }).getByRole("button").allTextContents(), ["Sat, Apr 10, 2027", "Sun, Apr 11, 2027"]);
      const savedSchedule = await page.evaluate(() => JSON.parse(localStorage.getItem("gymnastics-tab-sync")).schedule);
      assert.deepEqual(savedSchedule.days.map(day => day.isoDate), ["2027-04-10", "2027-04-11"]);
      await calendar.getByRole("heading", { name: "Reviewed juniors", exact: true }).waitFor();
      await calendar.getByRole("heading", { name: "Evening finals", exact: true }).waitFor();
      assert.equal(await calendar.getByText("3 sessions", { exact: true }).count(), 0, "sessions are exposed without the summary box");
      assert.equal(await calendar.getByRole("heading", { name: "Sat, Apr 10, 2027", exact: true }).count(), 0, "date appears only in the day tab");
      for (const name of ["Edit Saturday, April 10, 2027", "Remove day: Saturday, Apr 10"]) {
        const action = calendar.getByRole("button", { name, exact: true });
        assert.equal(await action.textContent(), "", "day controls use icons instead of button text");
        assert.equal(await action.locator("svg").count(), 1);
      }
      const cards = await calendar.locator("article").evaluateAll(items => items.map(item => ({ x: item.getBoundingClientRect().x, y: item.getBoundingClientRect().y })));
      assert.equal(cards.length, 3);
      if (width > 1000) {
        assert.ok(cards.every(card => Math.abs(card.y - cards[0].y) < 1), "three sessions fit in one desktop row");
        assert.ok(cards[0].x < cards[1].x && cards[1].x < cards[2].x);
      } else assert.ok(cards[0].y < cards[1].y && cards[1].y < cards[2].y, "phone sessions stack");
      await calendar.getByRole("button", { name: "Sun, Apr 11, 2027", exact: true }).click();
      await calendar.getByRole("heading", { name: "Senior session", exact: true }).waitFor();
      assert.equal(await calendar.getByRole("heading", { name: "Reviewed juniors", exact: true }).count(), 0);
      assert.equal(await dialog.isVisible(), false, "date switching does not open the editor");
      await calendar.getByRole("button", { name: "Sat, Apr 10, 2027", exact: true }).click();
      await calendar.getByRole("heading", { name: "Reviewed juniors", exact: true }).waitFor();
      await page.screenshot({ path: path.join(output, `schedule-exposed-sessions-${width}-${dark ? "dark" : "light"}.png`) });
      await page.getByRole("button", { name: "Edit Saturday, April 10, 2027", exact: true }).click();
      await dialog.getByRole("button", { name: "Done", exact: true }).click();
      await page.getByRole("heading", { name: "Reviewed juniors", exact: true }).waitFor();
      await page.getByRole("button", { name: "Edit schedule", exact: true }).click();
      mode = "slow";
      const snap = page.waitForEvent("filechooser");
      await dialog.getByRole("button", { name: "Take a photo", exact: true }).click();
      await (await snap).setFiles(file);
      await progress.getByRole("button", { name: "Cancel import", exact: true }).waitFor();
      await page.waitForFunction(() => document.querySelector('[aria-busy="true"]'));
      assert.equal(await progress.getByRole("progressbar").getAttribute("aria-valuenow"), null);
      await page.screenshot({ path: path.join(output, `schedule-processing-${width}-${dark ? "dark" : "light"}.png`) });
      while (!release) await new Promise(resolve => setTimeout(resolve, 10));
      await progress.getByRole("button", { name: "Cancel import", exact: true }).click();
      release(); release = null;
      await dialog.getByRole("button", { name: "Take a photo", exact: true }).waitFor();
      assert.equal(await dialog.getByRole("button", { name: "Take a photo", exact: true }).evaluate(el => el === document.activeElement), true, "cancel returns focus to camera action");
      mode = "error";
      await dialog.locator('input[capture="environment"]').setInputFiles(file);
      const failed = page.getByRole("dialog", { name: "Unable to read schedule", exact: true });
      await failed.getByRole("alert").getByText("Try a clearer schedule photo.", { exact: true }).waitFor();
      await failed.getByRole("button", { name: "Cancel", exact: true }).click();
      mode = "success";
      await dialog.locator('input[capture="environment"]').setInputFiles(file);
      await review.waitFor();
      await review.getByRole("button", { name: "Cancel", exact: true }).click();
      assert.equal(await review.count(), 0);
      await dialog.locator('input[capture="environment"]').setInputFiles(file);
      await review.waitFor();
      await review.getByRole("button", { name: "Close import results", exact: true }).click();
      await dialog.locator('input[capture="environment"]').setInputFiles(file);
      await review.waitFor();
      await page.keyboard.press("Escape");
      await review.waitFor({ state: "hidden" });
      assert.equal(await dialog.isVisible(), true, "Escape closes only the results popup");
      await dialog.getByRole("button", { name: "Done", exact: true }).click();
      await page.getByRole("heading", { name: "Authored finals", exact: true }).waitFor();
      await page.getByRole("heading", { name: "Reviewed juniors", exact: true }).waitFor();
      assert.equal(await page.getByRole("heading", { name: "Imported juniors", exact: true }).count(), 0);
      await page.evaluate(() => {
        const saved = JSON.parse(localStorage.getItem("gymnastics-tab-sync"));
        saved.schedule.days.push({ id: "retained-empty-sunday", isoDate: "2027-04-18", date: "Sunday, April 18, 2027", shortDate: "Sunday, Apr 18", sessions: [], source: { fileName: "old-import.jpg", importId: "old-source" } });
        localStorage.setItem("gymnastics-tab-sync", JSON.stringify(saved));
      });
      await page.goto(href.replace("&editing", ""));
      await page.getByRole("tab", { name: "Schedule", exact: true }).click();
      await calendar.getByRole("heading", { name: "Reviewed juniors", exact: true }).waitFor();
      assert.equal(await calendar.locator("article").count(), 3, "guest view opens the first day's sessions");
      assert.equal(await calendar.getByRole("button", { name: /Edit session|Remove session/ }).count(), 0);
      await calendar.getByRole("button", { name: "Sun, Apr 11, 2027", exact: true }).click();
      await calendar.getByRole("heading", { name: "Senior session", exact: true }).waitFor();
      await calendar.getByRole("button", { name: "Sun, Apr 18, 2027", exact: true }).click();
      await calendar.getByText("No event scheduled.", { exact: true }).waitFor();
      assert.equal(await calendar.locator("article").count(), 0);
      assert.equal(await calendar.getByText("Sessions to be announced.", { exact: true }).count(), 0);
    }
    assert.equal(requests, 24);
    assert.deepEqual(errors, []);
  } finally { release?.(); await browser.close(); }
});
