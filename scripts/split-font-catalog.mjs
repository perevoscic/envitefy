/** Keep the complete authored font catalog available outside the homepage critical path. */
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const root = fileURLToPath(new URL("../", import.meta.url));
const catalog = await readFile(path.join(root, "src/app/gallery-fonts.css"), "utf8");
const sharedFaces = [];
postcss.parse(catalog).walkAtRules("font-face", (face) => {
  const family = face.nodes.find((node) => node.prop === "font-family")?.value.replace(/['"]/g, "");
  // Raleway is the application's existing body fallback, including public dialogs.
  if (family === "Raleway") sharedFaces.push(face.toString());
});
if (!sharedFaces.length) throw new Error("The shared Raleway font registration is missing.");
const hash = createHash("sha256").update(catalog).digest("hex").slice(0, 12);
const relative = `fonts/gallery/catalog-${hash}.css`;
const outputs = new Map([
  [relative, catalog],
  ["../src/app/shared-gallery-fonts.css", `/* Generated by scripts/split-font-catalog.mjs. Keep authored descriptors unchanged. */\n${sharedFaces.join("\n\n")}\n`],
  ["../src/lib/font-catalog-stylesheet.ts", `// Generated by scripts/split-font-catalog.mjs. Content-versioned for immutable delivery.\nexport const FONT_CATALOG_STYLESHEET = "/${relative}";\n`],
]);
for (const [relativePath, content] of outputs) {
  const destination = path.resolve(root, "public", relativePath);
  if (process.argv.includes("--check")) {
    if (await readFile(destination, "utf8") !== content) throw new Error(`Outdated font delivery asset: ${relativePath}`);
  } else {
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, content);
  }
}
console.log(JSON.stringify({ catalog: `/${relative}`, catalogBytes: Buffer.byteLength(catalog), sharedFontFaces: sharedFaces.length }));
