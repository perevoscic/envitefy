export function authoredPageDirection(
  collection: ThemedEventCollectionId,
  subtype: string,
  sceneIndex: number,
  original: PageRecipe,
) {
  const family = EVENT_PAGE_THEME_PRESENTATIONS[collection][subtype];
  const direction = family && EVENT_PAGE_PRESENTATION_FAMILIES[family][sceneIndex];
  if (!direction)
    throw new Error(`Missing authored page direction: ${collection}/${subtype}/${sceneIndex}`);
  return {
    page: {
      ...original,
      editorLayout: direction.editorLayout,
      bodyPresentation: {
        ...original.bodyPresentation,
        alignment:
          direction.heading === "masthead" || direction.heading === "ribbon"
            ? ("center" as const)
            : ("left" as const),
        borderRadius: direction.radius,
        spacing: direction.spacing,
        bodyLayout: direction.layout,
        bodySurface: direction.surface,
        bodyHeading: direction.heading,
        bodyFlow: direction.flow,
      },
    },
    name: `${family}/${direction.name}`,
  };
}
