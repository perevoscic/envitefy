type Scene = { name: string; brief: string };
type AuthoredTheme = { name: string; subtype: string; palette: number; style: string; medium: string; scenes: Scene[] };
function theme(name: string, subtype: string, palette: number, style: string, medium: string, scenes: string[]): AuthoredTheme {
  return { name, subtype, palette, style, medium, scenes: scenes.map((entry) => {
    const [sceneName, ...brief] = entry.split("|");
    return { name: sceneName, brief: brief.join("|") };
  }) };
}

