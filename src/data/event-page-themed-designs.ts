const COMPOSITIONS: GeneralEventDesign["composition"][] = ["editorial", "arch", "panorama", "poster", "framed", "postcard", "journal", "organic", "oval"];
const EDITOR_LAYOUTS: ThemedEventEditorLayout[] = ["split", "banner", "poster", "editorial", "spotlight", "minimal", "cards"];
const SECTION_STYLES: ThemedEventBodyPresentation["sectionStyle"][] = ["cards", "ruled", "open", "panels", "timeline"];
const FONTS = [serif, sans, classic, display, serif, sans];
const slugify = (value: string) => value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

export const EVENT_PAGE_THEMED_DESIGNS: ThemedEventDesign[] = EVENT_PAGE_THEMED_COLLECTIONS.flatMap((collection) =>
  EVENT_PAGE_THEMED_BRIEFS[collection.id].flatMap((direction, themeIndex) => direction.scenes.map((scene, sceneIndex): ThemedEventDesign => {
    const palette = PALETTES[direction.palette];
    const slug = `${direction.subtype}-${slugify(scene.name)}`;
    const font = collection.category === "sports" && !["dance", "cheerleading"].includes(collection.id)
      ? [display, sans, classic, display, sans, serif][sceneIndex]
      : FONTS[(themeIndex + sceneIndex) % FONTS.length];
    return {
      id: `${collection.id}--${slug}`, collection: collection.id, slug,
      name: `${direction.name} · ${scene.name}`, coverTitle: scene.name,
      label: collection.id === "religious-events" ? direction.style : direction.name,
      description: `${direction.name}: ${scene.brief}.`, style: direction.style,
      artwork: `/templates/event-pages/${collection.id}/${slug}.webp`,
      composition: COMPOSITIONS[(themeIndex * 2 + sceneIndex) % COMPOSITIONS.length],
      background: palette.background, ink: palette.ink, accent: palette.accent, font,
      theme: { bg: palette.bg, text: palette.text, accent: palette.ac, preview: palette.bg, fontFamily: font },
      subtype: direction.subtype, tags: [collection.id, direction.subtype, direction.style, scene.name],
      scene: scene.brief,
      editorLayout: EDITOR_LAYOUTS[(themeIndex + sceneIndex) % EDITOR_LAYOUTS.length],
      bodyPresentation: {
        surface: [6, 7, 8, 9, 15, 16, 18].includes(direction.palette) ? "dark" : sceneIndex % 3 === 0 ? "paper" : "tinted",
        sectionStyle: SECTION_STYLES[(themeIndex + sceneIndex) % SECTION_STYLES.length],
        alignment: sceneIndex % 3 === 0 ? "center" : "left",
        borderRadius: ["0.25rem", "1.25rem", "0.75rem", "0rem", "1.5rem", "0.5rem"][sceneIndex],
        spacing: ["airy", "balanced", "compact", "airy", "balanced", "airy"][sceneIndex] as ThemedEventBodyPresentation["spacing"],
      },
    };
  })),
);
