type Recipe = readonly [
  slug: string,
  name: string,
  palette: keyof typeof PALETTES,
  motif: string,
  treatment: string,
  material: string,
];

function define(occasion: string, recipes: readonly Recipe[]): HolidayBackgroundPreset[] {
  return recipes.map(([slug, name, palette, motif, treatment, material]) => ({
    id: `${occasion}--${slug}`,
    occasion,
    name,
    ...PALETTES[palette],
    motif,
    treatment,
    material,
  }));
}

