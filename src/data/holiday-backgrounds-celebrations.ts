  lilac: ["#EEE8F8", "#3B2858", "#61377E", "#FAF7FF", "#B69EC9"],
  sea: ["#E1F2EF", "#1B4141", "#285F5E", "#F3FCF8", "#87B8AE"],
  sand: ["#F2E5CD", "#3C3528", "#755027", "#FFF6E5", "#B9A177"],
