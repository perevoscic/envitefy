  ivory: ["#FFF7E8", "#282522", "#874018", "#FFFCF5", "#C7AB78"],
  sage: ["#EEF3DF", "#223C2C", "#395C34", "#F9FCEF", "#9CAF78"],
  navy: ["#EEF1F6", "#18324C", "#713B36", "#FAFCFF", "#9AAFC6"],
  night: ["#112C40", "#F9F5E9", "#F3CA82", "#1B3C50", "#7795AF"],
  forest: ["#17392C", "#FFF9E9", "#EBD18A", "#214C37", "#8AAA8D"],
  berry: ["#3B1830", "#FFF5E8", "#F4C4CB", "#54213D", "#B98AAB"],
