backgroundsByOccasion.set("school", SCHOOL_BACKGROUNDS);
for (const preset of SCHOOL_BACKGROUNDS) backgroundsById.set(preset.id, preset);
for (const design of SCHOOL_EVENT_DESIGNS) {
  const preset = backgroundsById.get(design.backgroundId || "");
  if (!preset) throw new Error(`Unknown school background for ${design.id}`);
  defaultsByDesignId.set(design.id, preset);
}

// Old IDs retain their original paper until the owner explicitly chooses a new background.
for (const kind of ["weekly-memo", "field-trip", "school-celebration", "parent-meeting"]) {
  const current = SCHOOL_EVENT_DESIGNS.find(design => design.schoolTemplate === kind);
  const preset = backgroundsById.get(current?.backgroundId || "");
  if (preset) defaultsByDesignId.set(`school--${kind}`, preset);
}

/** Return only the named occasion's authored choices, in their curated display order. */
export function getHolidayBackgrounds(occasion?: string | null): HolidayBackgroundPreset[] {
  return [...(backgroundsByOccasion.get(occasion || "") || [])];
}

/** Invalid, unknown or cross-occasion choices safely resolve to the selected design's default. */
export function getHolidayBackground(designId?: string | null, choice?: unknown): HolidayBackgroundPreset | undefined {
  const fallback = defaultsByDesignId.get(designId || "");
  if (!fallback) return undefined;
  const normalized = normalizeHolidayBackgroundChoice(choice);
  const selected = normalized && backgroundsById.get(normalized.presetId);
  return selected && selected.occasion === fallback.occasion ? selected : fallback;
}

/** Reject arbitrary CSS, unknown presets and unsupported future payload versions. */
export function normalizeHolidayBackgroundChoice(value: unknown): HolidayBackgroundChoice | undefined {
  if (!value || typeof value !== "object" || Array.isArray(value)) return undefined;
  const choice = value as Record<string, unknown>;
  if (choice.version !== 1 || typeof choice.presetId !== "string" || !backgroundsById.has(choice.presetId)) return undefined;
  if (choice.source !== undefined && choice.source !== "template" && choice.source !== "custom") return undefined;
  return { version: 1, presetId: choice.presetId, ...(choice.source ? { source: choice.source } : {}) };
}

export function getHolidayBackgroundChoice(presetId: string, source: "template" | "custom" = "custom"): HolidayBackgroundChoice | undefined {
  return backgroundsById.has(presetId) ? { version: 1, presetId, source } : undefined;
}
