const backgroundsByOccasion = new Map<string, HolidayBackgroundPreset[]>();
const backgroundsById = new Map<string, HolidayBackgroundPreset>();
const defaultsByDesignId = new Map<string, HolidayBackgroundPreset>();
const additionalBackgrounds: Record<string, HolidayBackgroundPreset[]> = {
  ...HOLIDAY_BACKGROUND_CELEBRATIONS,
  ...HOLIDAY_BACKGROUND_CULTURAL_SEASONAL,
};
for (const [occasion, recipe] of Object.entries(RECIPES)) {
  const presets: HolidayBackgroundPreset[] = recipe.presets.map(([localId, name, page, ink, accent, surface, secondary, motif, treatment]) => ({
    id: `${occasion}--${localId}`, occasion, name, page, ink, accent, surface, secondary, motif, treatment,
  }));
  presets.push(...(additionalBackgrounds[occasion] || []));
  backgroundsByOccasion.set(occasion, presets);
  for (const preset of presets) {
    if (preset.occasion !== occasion || backgroundsById.has(preset.id)) {
      throw new Error(`Invalid or duplicate holiday background ${preset.id}`);
    }
    backgroundsById.set(preset.id, preset);
  }
  const defaultEntries = [
    ...Object.entries(recipe.defaults),
    ...Object.entries(EXPANSION_DEFAULTS[occasion as HolidayCollectionId]),
  ];
  for (const [slug, localId] of defaultEntries) {
    const preset = backgroundsById.get(`${occasion}--${localId}`);
    if (!preset) throw new Error(`Unknown holiday background for ${occasion}--${slug}`);
    const designId = `holidays--${occasion}--${slug}`;
    if (defaultsByDesignId.has(designId)) throw new Error(`Duplicate holiday background default for ${designId}`);
    defaultsByDesignId.set(designId, preset);
  }
}

